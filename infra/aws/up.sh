case "$STATUS" in
  "")
    MODE=create ;;
  CREATE_COMPLETE|UPDATE_COMPLETE|UPDATE_ROLLBACK_COMPLETE|IMPORT_COMPLETE)
    MODE=update ;;
  REVIEW_IN_PROGRESS)
    # 예전 실행이 미리보기만 만들고 멈춘 상태. 처음 만들기로 이어 간다.
    MODE=create ;;
  ROLLBACK_COMPLETE|ROLLBACK_FAILED|CREATE_FAILED|DELETE_FAILED)
    die "예전에 실패한 스택($STATUS)이 남아 있습니다. 'bash infra/aws/down.sh' 로 지운 뒤 다시 실행하세요." ;;
  *_IN_PROGRESS)
    die "스택에 다른 작업이 진행 중입니다($STATUS). 끝난 뒤 다시 실행하세요." ;;
  *)
    die "예상하지 못한 스택 상태입니다: $STATUS. AWS 콘솔 CloudFormation 화면에서 확인하세요." ;;
esac
if [ "$MODE" = create ]; then
  echo "  → 새로 만듭니다."
else
  echo "  → 이미 있습니다($STATUS). 바뀐 설정만 반영하고 DB 세팅을 다시 확인합니다."
fi

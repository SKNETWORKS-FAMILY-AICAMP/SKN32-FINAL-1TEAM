PARAMS=(
  "AdminCidr=$ADMIN_CIDR"
  "WebInstanceType=$WEB_INSTANCE_TYPE"
  "NoticeInstanceType=$NOTICE_INSTANCE_TYPE"
  "DbInstanceClass=$DB_INSTANCE_CLASS"
  "DbEngineVersion=$DB_ENGINE_VERSION"
  "DbAllocatedStorage=$DB_STORAGE_GB"
)
if [ "$MODE" = create ]; then
  pick_azs
  AMI_ID="$(awsq ssm get-parameter --name "$UBUNTU_AMI_PARAM" --query Parameter.Value)" \
    || die "이 리전의 Ubuntu 24.04 이미지를 찾지 못했습니다."
  echo "  가용영역: $PRIMARY_AZ (서버 · DB), $SECONDARY_AZ (RDS 예비 서브넷)"
  echo "  서버 이미지: Ubuntu 24.04 ($AMI_ID)"
  # 가용영역 · 이미지 · 내부 주소는 처음에만 넘긴다. 나중에 바뀌면 서버가 통째로 새로 만들어지기 때문이다.
  PARAMS+=(

parse_common_args "$@"
SKIP_DB=0
for a in ${EXTRA_ARGS[@]+"${EXTRA_ARGS[@]}"}; do
  case "$a" in
    --skip-db) SKIP_DB=1 ;;
    *) usage >&2; die "모르는 옵션: $a" ;;
  esac

#!/usr/bin/env bash
# shellcheck disable=SC2154  # OUT_* 변수는 load_outputs 가 printf -v 로 채운다
# S-Brain 원버튼 생성
#
#   bash infra/aws/up.sh                    # aws configure 의 기본 계정으로
#   bash infra/aws/up.sh --profile team     # 다른 계정(프로필)으로
#
# 한 번에 하는 일: VPC · 서브넷 · NAT → 웹 EC2 + 고정 IP 연결 → 공고 서버 EC2(사설망, 고정 내부 주소)
#                 → RDS MySQL → 테이블 생성 · 앱 계정 · 두 서버에 DB 접속 정보 파일(/etc/sbrain/db.env)
#
# 다시 실행해도 안전하다. 이미 있으면 바뀐 설정만 반영하고, DB 세팅은 아직 적용하지 않은 SQL 파일만 적용한다.
# 내 공인 IP 가 바뀌어 SSH 가 막혔을 때도 다시 실행하면 새 IP 로 열린다.
set -euo pipefail
# shellcheck source=infra/aws/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

usage() {
  cat <<'EOF'
사용법: bash infra/aws/up.sh [옵션]
  --profile 이름   다른 AWS 계정으로 만들 때 (aws configure --profile 이름 으로 미리 등록)
  --region 리전    리전 (기본: settings.env 의 REGION = ap-northeast-2 서울)
  --stack 이름     스택 이름 (기본: sbrain). 같은 계정에 한 벌 더 만들 때 다른 이름을 쓴다
  --yes            확인 질문 없이 진행
  --skip-db        서버 안 DB 세팅(테이블 생성 · 앱 계정 · 접속 정보 파일)을 건너뛴다
EOF
}


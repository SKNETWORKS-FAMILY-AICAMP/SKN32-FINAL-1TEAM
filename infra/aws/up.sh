# 탭·줄로 섞인 aws 결과를 한 줄에 하나씩, 중복 없이
as_lines() { tr '\t' '\n' | sed -e '/^$/d' -e '/^None$/d' | sort -u; }
in_list() { printf '%s\n' "$2" | grep -qx "$1"; }

check_x86() {
  local arch
  arch="$(awsq ec2 describe-instance-types --instance-types "$1" \
    --query 'InstanceTypes[0].ProcessorInfo.SupportedArchitectures' 2>/dev/null)" \
    || die "이 리전에 없는 서버 종류입니다: $1 (settings.env 에서 바꾸세요)"
  case "$arch" in
    *x86_64*) ;;
    *) die "$1 은 ARM 서버라 이 설계도(Ubuntu amd64)와 맞지 않습니다. x86 종류를 고르세요." ;;
  esac
}

# 계정마다 가용영역 이름이 가리키는 실제 위치가 다르고, 서버 종류를 못 쓰는 곳도 있다.
# 그래서 이름을 박아 두지 않고, 세 종류(웹 · 공고 서버 · DB)를 모두 쓸 수 있는 곳을 고른다.
pick_azs() {
  local zones web notice db z
  zones="$(awsq ec2 describe-availability-zones \
    --filters Name=zone-type,Values=availability-zone Name=state,Values=available \
    --query 'AvailabilityZones[].ZoneName' | as_lines)"
  web="$(awsq ec2 describe-instance-type-offerings --location-type availability-zone \
    --filters "Name=instance-type,Values=$WEB_INSTANCE_TYPE" --query 'InstanceTypeOfferings[].Location' | as_lines)"
  notice="$(awsq ec2 describe-instance-type-offerings --location-type availability-zone \
    --filters "Name=instance-type,Values=$NOTICE_INSTANCE_TYPE" --query 'InstanceTypeOfferings[].Location' | as_lines)"
  db="$(awsq rds describe-orderable-db-instance-options --engine mysql \
    --db-instance-class "$DB_INSTANCE_CLASS" \
    --query 'OrderableDBInstanceOptions[].AvailabilityZones[].Name' | as_lines)"
  [ -n "$web" ]    || die "이 계정·리전에서 웹 서버 종류 $WEB_INSTANCE_TYPE 를 쓸 수 없습니다."
  [ -n "$notice" ] || die "이 계정·리전에서 공고 서버 종류 $NOTICE_INSTANCE_TYPE 를 쓸 수 없습니다."
  [ -n "$db" ]     || die "이 계정·리전에서 DB 종류 $DB_INSTANCE_CLASS 를 쓸 수 없습니다."

  PRIMARY_AZ=""
  for z in $zones; do
    if in_list "$z" "$web" && in_list "$z" "$notice" && in_list "$z" "$db"; then
      PRIMARY_AZ="$z"
      break
    fi
  done
  [ -n "$PRIMARY_AZ" ] || die "웹 · 공고 서버 · DB 종류를 한곳에서 모두 쓸 수 있는 가용영역이 없습니다. 서버 종류를 바꾸세요."

  # RDS 는 가용영역 2곳의 서브넷을 요구한다. DB 를 쓸 수 있는 다른 곳을 먼저 고른다.
  SECONDARY_AZ=""
  for z in $db $zones; do
    if [ "$z" != "$PRIMARY_AZ" ] && in_list "$z" "$zones"; then
      SECONDARY_AZ="$z"
      break
    fi
  done
  [ -n "$SECONDARY_AZ" ] || die "이 리전에는 가용영역이 1곳뿐입니다. RDS 는 2곳이 필요합니다."
}

# SSH 키를 ~/.ssh 에 저장한다. 이미 같은 키가 있으면 그대로 둔다.
save_key() {
  local pub_aws pub_local=""
  mkdir -p "$HOME/.ssh"
  pub_aws="$(awsq ec2 describe-key-pairs --key-pair-ids "$OUT_KeyPairId" --include-public-key \
    --query 'KeyPairs[0].PublicKey' | awk 'NF {print $1" "$2; exit}')"
  if [ -f "$KEY_FILE" ] && command -v ssh-keygen >/dev/null 2>&1; then
    chmod 600 "$KEY_FILE" 2>/dev/null || true
    pub_local="$(ssh-keygen -y -f "$KEY_FILE" 2>/dev/null | awk 'NF {print $1" "$2; exit}' || true)"
  fi
  if [ -f "$KEY_FILE" ] && [ "$pub_local" = "$pub_aws" ]; then
    echo "  SSH 키: $KEY_FILE (이미 있음)"
    return 0
  fi
  if [ -f "$KEY_FILE" ]; then
    mv "$KEY_FILE" "$KEY_FILE.old-$(date +%Y%m%d%H%M%S)"
    warn "예전 스택의 키 파일을 $KEY_FILE.old-* 로 옮겼습니다."
  fi
  ( umask 077
    aws ssm get-parameter --name "/ec2/keypair/$OUT_KeyPairId" --with-decryption \
      --query Parameter.Value --output text | tr -d '\r' > "$KEY_FILE" )
  chmod 600 "$KEY_FILE" 2>/dev/null || true
  echo "  SSH 키: $KEY_FILE (새로 저장)"
}

write_ssh_config() {
  mkdir -p "$OUT_DIR"
  cat > "$OUT_DIR/ssh_config" <<EOF
# generated by infra/aws/up.sh
# usage: ssh -F $OUT_DIR/ssh_config $STACK_NAME-web

Host $STACK_NAME-web
  HostName $OUT_WebPublicIp
  User ubuntu
  IdentityFile ~/.ssh/$STACK_NAME-$REGION.pem
  IdentitiesOnly yes
  StrictHostKeyChecking accept-new

Host $STACK_NAME-notice
  HostName $OUT_NoticePrivateIp
  User ubuntu
  IdentityFile ~/.ssh/$STACK_NAME-$REGION.pem
  IdentitiesOnly yes
  StrictHostKeyChecking accept-new
  ProxyJump $STACK_NAME-web
EOF
}

# 서버로 보낼 묶음: DB 세팅 스크립트 + schema-order.txt 순서대로 번호를 붙인 SQL 사본
build_bundle() {
  local out="$BUILD_DIR/bootstrap" line n=0 name
  rm -rf "$BUILD_DIR"
  mkdir -p "$out/sql"
  tr -d '\r' < "$REL/bootstrap/setup-db.sh" > "$out/setup-db.sh"
  : > "$out/sql/order.tsv"
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"
    line="$(printf '%s' "$line" | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
    [ -n "$line" ] || continue
    [[ "$line" =~ ^[A-Za-z0-9_./-]+$ ]] || die "schema-order.txt 경로에 쓸 수 없는 글자가 있습니다: $line"
    [ -f "$line" ] || die "schema-order.txt 에 적힌 파일이 없습니다: $line"
    n=$((n + 1))
    name="$(printf '%02d_%s' "$n" "$(basename "$line")")"
    cp "$line" "$out/sql/$name"
    printf '%s\t%s\n' "$name" "$line" >> "$out/sql/order.tsv"
  done < "$REL/schema-order.txt"
  [ "$n" -gt 0 ] || die "schema-order.txt 에 SQL 파일이 하나도 없습니다."
  echo "  SQL 파일 ${n}개를 묶었습니다."
}

# 서버가 원격 실행(SSM)에 연결될 때까지 기다린다. 첫 부팅 뒤 1~3분 걸린다.
wait_ssm_online() {
  local id="$1" label="$2" st
  printf '  %s 원격 실행 연결 기다리는 중' "$label"
  for _ in $(seq 1 60); do
    st="$(awsq ssm describe-instance-information --filters "Key=InstanceIds,Values=$id" \
      --query 'InstanceInformationList[0].PingStatus' 2>/dev/null || true)"
    if [ "$st" = Online ]; then
      echo " → 연결됨"
      return 0
    fi
    printf '.'
    sleep 10
  done
  echo
  die "$label($id)이 10분 안에 원격 실행(SSM)에 연결되지 않았습니다. 서버 첫 부팅이 늦을 수 있으니 몇 분 뒤 up.sh 를 다시 실행하세요."
}

# 서버 안에서 setup-db.sh 를 실행하고 끝날 때까지 기다린다. 결과는 REMOTE_OUT · REMOTE_ERR.
run_remote() {
  local id="$1" tag="$2" label="$3"
  shift 3
  local dir=/opt/sbrain/bootstrap cmd cid status=Pending
  local params_file="$BUILD_DIR/ssm-$tag.json"
  # 첫 부팅 설치(aws CLI · mysql 클라이언트)가 끝나기를 최대 10분 기다린 뒤 실행한다.
  # (작은따옴표 그대로 서버에 보낸다. $PATH · $(seq) 는 서버에서 풀린다)
  # shellcheck disable=SC2016
  cmd='export PATH=$PATH:/snap/bin; for i in $(seq 1 120); do [ -f /var/lib/sbrain-userdata.done ] && break; sleep 5; done; '
  cmd+="mkdir -p $dir && aws s3 sync s3://$OUT_DeployBucketName/bootstrap $dir --delete --only-show-errors --region $REGION"
  cmd+=" && bash $dir/setup-db.sh $*"
  # shellcheck disable=SC1003
  case "$cmd" in *'"'*|*'\'*) die "원격 명령에 따옴표·역슬래시가 들어갔습니다: $cmd" ;; esac
  printf '{"commands":["%s"],"executionTimeout":["1800"]}\n' "$cmd" > "$params_file"

  cid="$(awsq ssm send-command --instance-ids "$id" --document-name AWS-RunShellScript \
    --comment "sbrain $tag db setup" --timeout-seconds 600 \
    --parameters "file://$params_file" --query Command.CommandId)" \
    || die "$label 에 원격 실행을 보내지 못했습니다."

  printf '  %s 에서 실행 중' "$label"
  for _ in $(seq 1 240); do
    sleep 5
    status="$(awsq ssm get-command-invocation --command-id "$cid" --instance-id "$id" \
      --query Status 2>/dev/null || echo Pending)"
    case "$status" in
      Pending|InProgress|Delayed) printf '.' ;;
      *) break ;;
    esac
  done
  echo " → $status"
  REMOTE_OUT="$(awsq ssm get-command-invocation --command-id "$cid" --instance-id "$id" \
    --query StandardOutputContent 2>/dev/null || true)"
  REMOTE_ERR="$(awsq ssm get-command-invocation --command-id "$cid" --instance-id "$id" \
    --query StandardErrorContent 2>/dev/null || true)"
  [ "$status" = Success ] && return 0

  explain_remote_error "$label"
  if [ -n "$REMOTE_ERR" ]; then
    { echo "--- $label 오류 출력 (마지막 20줄) ---"; printf '%s\n' "$REMOTE_ERR" | tail -20; } >&2
  fi
  die "$label DB 세팅 실패 (상태: $status). 원인을 고친 뒤 up.sh 를 다시 실행하면 이어서 합니다."
}

# setup-db.sh 는 '@@ 키 값' 형식의 영어 한 줄로만 보고한다(윈도우 aws.exe 가 한글을 깨뜨릴 수 있어서).
# 여기서 한국어로 바꿔 보여 준다.
report_remote() {
  local label="$1" line key rest sub path
  while IFS= read -r line; do
    case "$line" in "@@ "*) ;; *) continue ;; esac
    line="${line#@@ }"
    key="${line%% *}"
    rest="${line#"$key"}"
    rest="${rest# }"
    case "$key" in
      db_ready)    echo "  [$label] DB 접속 확인" ;;
      database)    echo "  [$label] 데이터베이스 준비: $rest" ;;
      schema)
        read -r sub path <<< "$rest"
        case "$sub" in
          applied) echo "  [$label] 테이블 적용: $path" ;;
          skipped) echo "  [$label] 이미 적용됨(건너뜀): $path" ;;
          changed) warn "[$label] 이미 적용한 파일의 내용이 바뀌었습니다. 자동으로 다시 적용하지 않습니다: $path" ;;
        esac ;;
      app_user)    echo "  [$label] 앱 DB 계정 준비: $rest" ;;
      env_written) echo "  [$label] 앱 접속 정보 파일 작성: $rest" ;;
      tables)      echo "  [$label] 앱 계정으로 접속 성공 — 테이블 ${rest}개" ;;
    esac
  done <<< "$REMOTE_OUT"
}

explain_remote_error() {
  local label="$1" line code detail
  line="$(printf '%s\n' "$REMOTE_OUT" | grep '^@@ error ' | tail -1 || true)"
  line="${line#@@ error }"
  code="${line%% *}"
  detail="${line#"$code"}"
  report_remote "$label"
  case "$code" in
    tools_missing)  echo "  → 서버 첫 부팅 설치(aws CLI · mysql 클라이언트)가 아직 안 끝났거나 실패했습니다. 몇 분 뒤 다시 실행하세요. 서버 로그: /var/log/sbrain-userdata.log" >&2 ;;
    secret_read)    echo "  → AWS 비밀값(DB 비밀번호)을 읽지 못했습니다. 서버 권한(IAM 역할)을 확인하세요." >&2 ;;
    ca_download)    echo "  → RDS 인증서를 내려받지 못했습니다. 서버의 인터넷 연결(NAT)을 확인하세요." >&2 ;;
    db_unreachable) echo "  → DB 에 접속하지 못했습니다. RDS 가 켜져 있는지, 보안그룹 3306 을 확인하세요." >&2 ;;
    schema_failed)  echo "  → SQL 파일 적용 중 오류가 났습니다. 파일을 고친 뒤 다시 실행하면 그 파일부터 이어서 합니다." >&2 ;;
    bad_input)      echo "  → 서버에 넘긴 값이 이상합니다." >&2 ;;
    "")             echo "  → 서버 안 세팅이 중간에 멈췄습니다." >&2 ;;
    *)              echo "  → 서버 안 세팅 오류: $code" >&2 ;;
  esac
  [ -n "${detail# }" ] && echo "  원문:${detail}" >&2
  return 0
}


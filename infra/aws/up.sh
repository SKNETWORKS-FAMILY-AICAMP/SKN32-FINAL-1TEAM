  if [ "$MODE" = create ]; then
    die "만들기에 실패해 AWS 가 만들던 것을 되돌렸습니다. 위 원인을 확인한 뒤 'bash infra/aws/down.sh' → 다시 up.sh 를 실행하세요."
  fi
  die "설정 반영에 실패해 AWS 가 이전 상태로 되돌렸습니다. 위 원인을 확인하세요."

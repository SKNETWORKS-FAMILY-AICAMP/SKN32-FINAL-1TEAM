  build_bundle
  aws s3 sync "$BUILD_DIR/bootstrap" "s3://$OUT_DeployBucketName/bootstrap" --delete --only-show-errors
  DB_ARGS=(--region "$REGION" --db-host "$OUT_DbEndpoint" --db-port "$OUT_DbPort" --db-name "$DB_NAME"

#!/usr/bin/env bash
# 웹 서버(EC2) 안에서 root 로 실행된다. infra/aws/app-env.sh 가 원격 실행(SSM)으로 부르므로 손으로 부를 일은 거의 없다.
#
#   write-app-env.sh --region <리전> --stack <스택> --bucket <S3 버킷>
#
# SSM Parameter Store(/<스택>/app/*, SecureString)의 값과 up.sh 가 만든 /etc/sbrain/db.env 로 env 파일 둘을 만든다.
#   /etc/sbrain/worker.env — 워커(sbrain-worker.service)가 읽는다
#   /etc/sbrain/web.env    — 웹 백엔드(sbrain-web.service)가 읽는다. MYSQL_* 는 db.env 를 함께 읽는다
# 두 파일 모두 root 만 읽는다(600). systemd 가 root 로 읽어 앱 프로세스에 넘긴다.
# 앱이 이미 떠 있으면 새 값을 읽도록 다시 띄운다(워커는 하던 단계를 끝낸 뒤 — 최대 15분).
#
# 표준출력은 up.sh · setup-db.sh 와 같이 '@@ 키 값' 형식의 영어 한 줄만 쓴다(윈도우 aws.exe 가 한글을 깨뜨릴 수 있어서).
# 값은 출력하지 않는다 — 이름만 쓴다. 몇 번을 다시 실행해도 안전하다.
set -euo pipefail
export PATH="$PATH:/snap/bin"

say()  { echo "@@ $*"; }
fail() { say "error $*"; exit 1; }

REGION="" STACK="" BUCKET=""
while [ $# -gt 0 ]; do
  [ $# -ge 2 ] || fail "bad_input missing value for $1"
  case "$1" in
    --region) REGION="$2" ;;
    --stack)  STACK="$2" ;;
    --bucket) BUCKET="$2" ;;
    *)        fail "bad_input unknown option $1" ;;
  esac
  shift 2
done
[[ "$REGION" =~ ^[a-z0-9-]+$ ]]                 || fail "bad_input region"
[[ "$STACK" =~ ^[A-Za-z][A-Za-z0-9-]{0,31}$ ]]  || fail "bad_input stack"
[[ "$BUCKET" =~ ^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$ ]] || fail "bad_input bucket"

for tool in aws python3; do
  command -v "$tool" >/dev/null 2>&1 || fail "tools_missing $tool"
done
ETC=/etc/sbrain
[ -f "$ETC/db.env" ] || fail "db_env_missing run infra/aws/up.sh first"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# 값(JSON)을 파일로 받는다. snap 으로 깐 aws CLI 는 SSM 원격 실행 안에서 표준출력을 파일로 바로 돌리면
# 오류 없이 0바이트를 쓴다(setup-db.sh 와 같은 이유) — cat 을 거쳐 저장하고, 비었으면 멈춘다.
( umask 077
  aws ssm get-parameters-by-path --region "$REGION" --path "/$STACK/app" --with-decryption \
    --output json 2> "$WORK/aws.err" | cat > "$WORK/params.json" ) \
  || fail "param_read $(head -c 300 "$WORK/aws.err" | tr '\n' ' ')"
[ -s "$WORK/params.json" ] || fail "param_read empty output from aws cli $(head -c 300 "$WORK/aws.err" | tr '\n' ' ')"

python3 - "$WORK/params.json" "$ETC/db.env" "$STACK" "$BUCKET" "$REGION" "$WORK" <<'PY'
import json, os, re, sys

params_path, db_env_path, stack, bucket, region, out_dir = sys.argv[1:7]
prefix = '/%s/app/' % stack

vals = {}
for p in json.load(open(params_path)).get('Parameters', []):
    if p['Name'].startswith(prefix):
        vals[p['Name'][len(prefix):]] = p['Value']

db = {}
for line in open(db_env_path):
    line = line.strip()
    if line and not line.startswith('#') and '=' in line:
        k, v = line.split('=', 1)
        db[k.strip()] = v.strip()


def stop(msg):
    print('@@ error ' + msg)
    sys.exit(3)


# systemd EnvironmentFile 은 따옴표 · 빈칸 · 역슬래시를 따로 풀어 읽는다. 그런 글자가 든 값은 받지 않는다(이름만 알린다).
SAFE = re.compile(r'^[A-Za-z0-9._~:/?#@!+=,%-]+$')
REQUIRED = ('OPENAI_API_KEY', 'GOOGLE_CLIENT_ID', 'JWT_SECRET')
OPTIONAL = ('NTS_SERVICE_KEY', 'SBRAIN_NOTICE_API_URL')

missing = [n for n in REQUIRED if not vals.get(n)]
if missing:
    stop('param_missing ' + ','.join(missing))
for n, v in sorted(vals.items()):
    if not SAFE.match(v):
        stop('bad_value ' + n)
for k in ('MYSQL_HOST', 'MYSQL_PORT', 'MYSQL_DATABASE', 'MYSQL_USER', 'MYSQL_PASSWORD'):
    if not db.get(k) or not SAFE.match(db[k]):
        stop('db_env_incomplete ' + k)

# 산출물 파일 저장소 — 웹과 워커가 같은 값을 본다(결정 0035). 버킷의 app/ 아래라 템플릿 권한(app/*) 안이다.
artifact_root = 's3://%s/app/artifacts/' % bucket
# 비밀번호는 영문 · 숫자뿐이라(setup-db.sh 규칙) URL 이스케이프가 필요 없다.
db_url = 'mysql+pymysql://%s:%s@%s:%s/%s?charset=utf8mb4' % (
    db['MYSQL_USER'], db['MYSQL_PASSWORD'], db['MYSQL_HOST'], db['MYSQL_PORT'], db['MYSQL_DATABASE'])

worker = [
    ('SBRAIN_DB_URL', db_url),
    ('OPENAI_API_KEY', vals['OPENAI_API_KEY']),
    ('SBRAIN_ARTIFACT_ROOT', artifact_root),
    ('AWS_REGION', region),
    ('SBRAIN_WORKER_LOG_DIR', '/var/log/sbrain/worker'),
    ('SBRAIN_WORKER_LOG_KEEP_DAYS', '366'),
    # 서버 설치본에는 시장 자료 파일이 없어 실행별 KIET 검색으로 시장 근거를 얻는다(운영 워커만, 사용자 결정 2026-10-16)
    ('SBRAIN_KIET_SEARCH', '1'),
]
if vals.get('SBRAIN_NOTICE_API_URL'):
    worker.append(('SBRAIN_NOTICE_API_URL', vals['SBRAIN_NOTICE_API_URL']))

web = [
    ('GOOGLE_CLIENT_ID', vals['GOOGLE_CLIENT_ID']),
    ('JWT_SECRET', vals['JWT_SECRET']),
    ('SBRAIN_ARTIFACT_ROOT', artifact_root),
    ('AWS_REGION', region),
    # 오케스트레이터의 사업비 · 일정 필수 확인(PLAN_TABLES_REQUIRED)이 켜져 있어 웹도 같이 켠다
    ('REQUIRE_BUDGET_SCHEDULE', '1'),
    ('COOKIE_SECURE', '1'),
    ('RHWP_BIN', '/opt/sbrain/bin/rhwp'),
]
if vals.get('NTS_SERVICE_KEY'):
    web.append(('NTS_SERVICE_KEY', vals['NTS_SERVICE_KEY']))


def write(name, rows):
    fd = os.open(os.path.join(out_dir, name), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as f:
        f.write('# generated by infra/aws/app/write-app-env.sh - change values with infra/aws/app-env.sh, not here\n')
        for k, v in rows:
            f.write('%s=%s\n' % (k, v))


write('worker.env', worker)
write('web.env', web)
absent = [n for n in OPTIONAL if not vals.get(n)]
if absent:
    print('@@ optional_missing ' + ','.join(absent))
PY

install -m 600 -o root -g root "$WORK/worker.env" "$ETC/worker.env"
install -m 600 -o root -g root "$WORK/web.env" "$ETC/web.env"
say "env_written $ETC/worker.env $ETC/web.env"

# 이미 떠 있는 앱만 다시 띄워 새 값을 읽게 한다(떠 있지 않으면 아무것도 하지 않는다)
if systemctl is-active --quiet sbrain-web 2>/dev/null; then
  systemctl try-restart sbrain-web && say "web restarted"
fi
if systemctl is-active --quiet sbrain-worker 2>/dev/null; then
  systemctl try-restart sbrain-worker && say "worker restarted"
fi

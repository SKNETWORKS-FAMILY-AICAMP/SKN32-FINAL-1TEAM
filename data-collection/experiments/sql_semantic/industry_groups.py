# '양식'은 음식(서양식)과 양식업(수산) 모두 — 양식업은 A 로 잡고 I 에서는 뺀다(group_of 참조)

# 표준 대분류를 하나도 못 찾았을 때 X 로 볼 분야·정책 범주 핵심어
FIELD_WORDS = ('바이오', '헬스케어', 'AI', '인공지능', '로봇', '팹리스', '수소', '방산', '국방', '모빌리티', '딥테크',
               '지식기반', '지식서비스', '지식산업', '지식정보', '주력산업', '신성장', '소재', '부품', '장비', '첨단',
               '가상융합', '4차산업', '서비스', 'IP', 'AX', '관광', '신산업', '뿌리', '스마트', '소부장', '초격차',
               '혁신기술', '산업', '분야')

_DROP = re.compile(r'[\s·ㆍ・‧∙‥…․\-_/\'‘’"“”]')


def _norm(text):
    return _DROP.sub('', text or '')


def _division_letter(num):
    for (lo, hi), letter in _DIVISIONS:
        if lo <= num <= hi:
            return letter
    return None


# 여러 업종을 잇는 말 — 이것으로 나눈 조각마다 따로 묶는다("건설업 및 제조업" → F, C)
_SPLIT = re.compile(r'\s*(?:및|또는|,|，|、|·|ㆍ|・|‧|∙|/)\s*|\s(?:와|과)\s')


# KSIC 세부 번호(세~다섯 자리) — "390 환경정화…", "(5616)", "47811 중 약국", "(94110∼94990)"
#   앞 두 자리가 중분류다. 뒤에 년·대·개 등이 붙은 숫자("100대 생활업종", "2024년")와 연도 모양 네 자리는 뺀다
_CODE_FINE = re.compile(r'(?<![\d.,A-Za-z])(\d{3,5})(?![\d.년원%대개명호조차종억만천위평㎡제]|\s*(?:평|㎡|제곱))')

# 나누기 전에 찾을 공식 명칭 — 글자 사이의 띄어쓰기·가운뎃점·쉼표는 무시한다
_SEP = r"[\s·ㆍ・‧∙‥…․\-_/'‘’\"“”,，、]*"
_SECTION_RE = sorted(((re.compile(_SEP.join(re.escape(ch) for ch in phrase)), letter, len(phrase))
                      for letter, phrases in SECTION_PHRASES for phrase in phrases), key=lambda x: -x[2])
_MARK = re.compile(r'§([A-U])§')


def _mark_sections(raw):
    """공식 명칭을 '§M§' 같은 표시로 바꾼다. 표시는 나누는 기호를 담지 않아 한 조각으로 남는다."""
    for rx, letter, _n in _SECTION_RE:
        raw = rx.sub(' §%s§ ' % letter, raw)
    return raw


def _explicit_codes(raw):
    codes = []
    fine = [] if '산재' in raw else _CODE_FINE.finditer(raw)   # 산재보험 업종코드는 KSIC 가 아니다
    for m in fine:
        num = m.group(1)
        if len(num) == 4 and 1990 <= int(num) <= 2039:
            continue                          # 연도일 수 있다
        letter = _division_letter(int(num[:2]))
        if letter:
            codes.append(letter)
    for m in _CODE_LETTER.finditer(raw):
        codes.append(m.group(1) or m.group(2))
    has_context = any(w in raw for w in _CODE_CONTEXT)
    for m in _CODE_DIVISION.finditer(raw):
        num = m.group(1) or m.group(2)
        if m.group(1) and not has_context:
            continue                          # "(72)" 처럼 체계가 밝혀지지 않은 괄호 숫자는 믿지 않는다
        letter = _division_letter(int(num))
        if letter:
            codes.append(letter)
    return list(dict.fromkeys(codes))


_PAREN = re.compile(r'[(（]([^()（）]*)[)）]')


def _part_groups(part):
    """조각 하나 → 대분류 목록. 괄호 밖 본문으로 정하고, 괄호 안은 "…포함"일 때만 덧붙인다(2026-09-28 F2).

    "제조기업(S/W포함)" → C, J. "(전력)반도체 … 제조기업" → C(괄호 속 '전력'으로 D 를 붙이지 않는다).
    "건설업 본사(산재보험 업종코드 …)" → F(괄호 속 '보험'으로 K 를 붙이지 않는다). 본문에 핵심어가 없으면 전체로 본다.
    """
    main = _PAREN.sub(' ', part)
    head = _part_group(main) if _norm(main) else None
    if head is None:
        head = _part_group(part)
    out = [head] if head else []
    for inner in _PAREN.findall(part):
        if '포함' in inner:
            out.extend(g for g in (_part_group(p) for p in _SPLIT.split(inner.replace('포함', ' '))) if g)
    return out


def _part_group(part):
    """조각 하나 → 대분류 하나 또는 None. 핵심어가 여럿이면 **가장 뒤(머리말)** 를 고른다.

    "음식료품 도매업" → 도매(G), "여객자동차운송업체" → 운송(H), "수산가공품 생산" → 생산(C).
    """
    mark = _MARK.search(part)
    if mark:
        return mark.group(1)
    t = _norm(part)
    if not t:
        return None
    if t in EXACT_PARTS:
        return EXACT_PARTS[t]
    if _AQUA.search(part) or _AQUA.search(t):
        return 'A'
    for words, letter in EXCLUSIVE:
        if any(w in t for w in words):
            return letter
    best = None                               # (끝 위치, 대분류)
    for letter, words in KEYWORDS:
        for w in words:
            i = t.rfind(w)
            if i >= 0 and (best is None or i + len(w) > best[0]):
                best = (i + len(w), letter)
    return best[1] if best else None


def group_of(text):
    """원문 업종 표현 하나 → 묶음 코드 목록(순서 유지, 중복 없음). 못 묶으면 [].

    분류 번호가 밝혀져 있는데 이름의 핵심어와 다른 대분류를 가리키면 한쪽을 고르지 않고 '?'(모호).
    """
    raw = text or ''
    t = _norm(raw)
    if not t:
        return []
    if any(w in t for w in ALL_WORDS) or t in ('전업종', '全업종'):
        return ['ALL']
    for words, letter in PHRASES:
        if any(w in t for w in words):
            return [letter]
    marked = _mark_sections(re.sub(r'S\s*[/.]\s*W', 'SW', raw))     # "S/W"·"S.W" 가 나뉘지 않게
    parts = [p for p in _SPLIT.split(marked) if p and p.strip()]
    found = [g for p in parts for g in _part_groups(p)]
    found = list(dict.fromkeys(found))
    explicit = _explicit_codes(raw)
    if explicit:
        if found and not set(found) & set(explicit):
            return ['?']
        return explicit
    if found:
        return found
    if any(w in t for w in FIELD_WORDS):
        return ['X']
    return []


def groups_of(texts):
    """여러 표현 → 묶음 합집합(순서 유지)."""
    out = []
    for t in texts:
        out.extend(group_of(t))
    return list(dict.fromkeys(out))


def applicant_section(text):
    """신청자 주 업종 입력 하나 → KSIC 대분류 하나(A~U). 하나로 정할 수 없으면 None.

    대분류 문자("C")를 그대로 받으면 그 값을 쓴다(화면이 목록에서 고르게 할 때). 자유 입력은 공고 쪽과 **같은**
    group_of 규칙으로 바꾼다 — 같은 규칙이어야 양쪽 코드가 맞는다. 둘 이상의 대분류·분야(X)·모호(?)는 None:
    신청자 업종을 모르면 업종으로 순서를 바꾸지 않는다.
    """
    raw = (text or '').strip()
    if raw.upper() in SECTIONS:
        return raw.upper()
    groups = group_of(raw)
    if len(groups) == 1 and groups[0] in SECTIONS:
        return groups[0]
    return None


# 업종 이름처럼 보여도 범위가 넓은 표현 — "IT 서비스·솔루션 분야", "의료·바이오 산업", "이차전지산업 관련 기업",
# "농림축산식품 수출업체". 대분류 하나로 좁혀 "목록 밖"이라 하면 틀린다(2026-09-28 업종 순위 안전 확인에서 발견).
# '수산업'은 업종이라 뺀다
_BROAD = re.compile(r'분야|(?<!수)산업|관련|연관|유관|전후방|수출')
# 제조업(C)으로 묶인 값은 "만든다"는 말이 직접 있어야 순위에 쓴다. "식품기업"·"의료기기"·"섬유ㆍ의류 소재기업"은
# 유통·판매·외식일 수도 있다(2026-09-28 Codex 통합 검수 P2 — bizinfo:PBLN_000000000125847 "식품기업"이 C 로만 읽혀 순위가 밀림)
_MAKES = re.compile(r'제조|생산|가공|제작|공장|뿌리|KSIC|산업분류|(?<![A-Za-z])C\s?\d{2}')


def allowed_sections(texts):
    """공고의 허용 업종 목록 → KSIC 대분류 집합. 비교할 수 없으면 None.

    값 하나라도 표준 대분류로 못 바꾸면(분야 X·모호 ?·미분류 []) None 이다. 예: 허용 목록이 [제조업, 바이오]일 때
    바이오 기업은 제조업이 아닐 수도, 맞을 수도 있다 — 대분류 집합 {C} 만 보고 "목록 밖"이라 하면 틀린다.
    '전 업종'(ALL)도 None — 제한이 없으니 비교할 것이 없다. 빈 목록도 None.
    분야·산업·관련·수출처럼 범위가 넓은 표현(_BROAD)이 하나라도 있으면 None — 순위에 쓰는 값이라 보수적으로 둔다.
    """
    out = set()
    for t in texts or []:
        if _BROAD.search(_norm(t)):
            return None
        groups = group_of(t)
        if 'C' in groups and not _MAKES.search(t or ''):
            return None
        if not groups or any(g not in SECTIONS for g in groups):
            return None
        out.update(groups)
    return out or None
